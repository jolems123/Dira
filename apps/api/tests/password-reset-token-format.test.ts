import { describe, expect, it } from 'vitest';
import { validPasswordResetToken } from '../src/lib/password-reset-token-format';

describe('password reset token format', () => {
  it('accepts the 32-byte lowercase hexadecimal token generated by forgot-password', () => {
    expect(validPasswordResetToken('ab'.repeat(32))).toBe(true);
  });
  it('rejects missing, oversized, short, uppercase, encoded and non-hex credentials', () => {
    for (const value of [undefined, null, 123, '', 'a'.repeat(63), 'a'.repeat(65), 'a'.repeat(100000), 'A'.repeat(64), 'g'.repeat(64), '%61'.repeat(22), 'a'.repeat(63) + '\n']) {
      expect(validPasswordResetToken(value)).toBe(false);
    }
  });
});
