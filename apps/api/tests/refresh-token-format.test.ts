import { describe, expect, it } from 'vitest';
import { validRefreshToken } from '../src/lib/refresh-token-format';

describe('refresh credential format', () => {
  it('accepts the exact 48-byte hex credential generated by auth', () => {
    expect(validRefreshToken('ab'.repeat(48))).toBe(true);
  });
  it('rejects empty, short, oversized and non-string credentials', () => {
    for (const value of [undefined, null, '', 'a'.repeat(95), 'a'.repeat(97), 'a'.repeat(100000), 123]) {
      expect(validRefreshToken(value)).toBe(false);
    }
  });
  it('rejects invalid characters, encoded values and whitespace', () => {
    for (const value of ['g'.repeat(96), 'A'.repeat(96), 'a'.repeat(95) + ' ', '%61'.repeat(32), 'a'.repeat(95) + '\n']) {
      expect(validRefreshToken(value)).toBe(false);
    }
  });
});
